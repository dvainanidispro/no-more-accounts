<?php
/**
 * Κώδικας εγκατάστασης του plugin (activation hook).
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Εκτελείται κατά την ενεργοποίηση του plugin.
 *
 * Δημιουργεί τα options με προεπιλογή "ανενεργό". Η add_option()
 * δεν αλλάζει υπάρχουσες τιμές σε επανενεργοποίηση του plugin.
 * Τα triggers ΔΕΝ δημιουργούνται εδώ — μόνο από τη σελίδα ρυθμίσεων,
 * ώστε τυχόν σφάλματα (π.χ. δικαιώματα) να εμφανίζονται καθαρά.
 */
function nma_install() {
	add_option( 'nma_prevent_users', '0' );
	add_option( 'nma_prevent_admins', '0' );
}

/**
 * Εκτελείται κατά την απενεργοποίηση του plugin.
 *
 * Αφαιρεί τα triggers από τη βάση: απενεργοποιημένο plugin σημαίνει
 * απενεργοποιημένη προστασία, αλλιώς το trigger θα συνέχιζε να
 * μπλοκάρει εγγραφές χωρίς να υπάρχει διαθέσιμο UI ελέγχου.
 * Τα options διατηρούνται.
 */
function nma_deactivate() {
	nma_drop_triggers();
}
